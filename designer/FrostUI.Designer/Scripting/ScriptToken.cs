namespace FrostUI.Designer.Scripting;

internal enum TokenType
{
    EndOfFile,
    Identifier,
    Number,
    String,
    Let,
    Global,
    If,
    Then,
    Else,
    Loop,
    ForEach,
    In,
    Function,
    Return,
    Break,
    Continue,
    True,
    False,
    Null,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    Assign,
    Equal,
    NotEqual,
    Less,
    Greater,
    LessEqual,
    GreaterEqual,
    AndAnd,
    OrOr,
    Bang,
    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,
    Comma,
    Colon,
    Semicolon,
    Dot,
}

internal readonly record struct Token(
    TokenType Type,
    string Text,
    int Line,
    int Column,
    double Number = 0);
